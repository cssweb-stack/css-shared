"""Fast, read-only metadata checks for a built unit; relevance needs human review."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit
import argparse, collections, json, re

ROOT=Path(__file__).resolve().parents[1]
cli=argparse.ArgumentParser()
cli.add_argument('unit')
cli.add_argument('--launch',action='store_true',help='Also fail if indexing remains disabled')
cli.add_argument('--output',type=Path,help='Save measured JSON results')
args=cli.parse_args()
if not re.fullmatch(r'[a-z0-9-]+',args.unit):cli.error('Invalid unit abbreviation')
project=ROOT.parent/args.unit;unit=ROOT/'src/data/units'/args.unit
settings=json.loads((unit/'site-settings.json').read_text())
identity=json.loads((unit/'unit-details.json').read_text())
origin=settings.get('url','').rstrip('/')
class Page(HTMLParser):
 def __init__(self):
  super().__init__();self.titles=[];self.h1s=[];self.metas=collections.defaultdict(list);self.canonicals=[];self.active=None;self.text=[];self.lang=None
 def handle_starttag(self,t,a):
  a=dict(a)
  if t=='html':self.lang=a.get('lang')
  if t in ['title','h1']:self.active=t;self.text=[]
  if t=='meta':
   key=a.get('name') or a.get('property')
   if key:self.metas[key.lower()].append(a.get('content',''))
  if t=='link' and 'canonical' in a.get('rel','').split():self.canonicals.append(a.get('href',''))
 def handle_data(self,s):
  if self.active:self.text.append(s)
 def handle_endtag(self,t):
  if t==self.active:
   (self.titles if t=='title' else self.h1s).append(re.sub(r'\s+',' ',' '.join(self.text)).strip());self.active=None
errors=[];notes=[];pages=[]
files=sorted((project/'_site').rglob('*.html'))
if not files:cli.error('Build the unit first')
for file in files:
 content=file.read_text()
 if content.startswith("<!-- Generated by shared URL migration; do not edit. -->"):continue
 scan=Page();scan.feed(content);rel=file.relative_to(project/'_site');url='/'+str(rel).replace('index.html','') if rel.name=='index.html' else '/'+str(rel)
 issue=lambda msg:errors.append(url+': '+msg)
 if len(scan.titles)!=1 or not scan.titles[0]:issue('Expected one nonempty title')
 if len(scan.h1s)!=1 or not scan.h1s[0]:issue('Expected one nonempty H1')
 descriptions=scan.metas['description']
 if len(descriptions)!=1 or not descriptions[0] or 'This will be the meta description' in descriptions[0]:issue('Missing, duplicate or placeholder description')
 title=scan.titles[0] if scan.titles else '';h1=scan.h1s[0] if scan.h1s else '';description=descriptions[0] if descriptions else ''
 base=title.removesuffix(' | '+identity['name'])
 normalize=lambda s:re.sub(r'\s+',' ',s.casefold()).strip()
 shortened=h1.removeprefix(identity['shortName']+': ')
 title_match=normalize(base) in [normalize(h1),normalize(shortened)]
 if not title_match:notes.append(url+': Review title/H1 wording alignment')
 if len(title)>80:notes.append(url+': Long rendered title; review meaning, do not truncate to an arbitrary limit')
 if not scan.lang:issue('Missing document language')
 is_error=url=='/404.html'
 if is_error:
  if scan.canonicals:issue('404 should not declare a canonical URL')
 elif len(scan.canonicals)!=1:notes.append(url+': Missing or duplicate canonical URL')
 elif scan.canonicals[0]!=origin+url:issue('Canonical differs from configured production URL')
 robots=','.join(scan.metas['robots']).lower()
 if is_error and 'noindex' not in robots:issue('404 must remain noindex')
 if args.launch and not is_error and ('noindex' in robots or settings.get('indexingEnabled') is not True):issue('Indexing disabled at launch')
 for key,expected in [('og:title',title),('twitter:title',title),('og:description',description),('twitter:description',description)]:
  if scan.metas[key]!=[expected]:issue(key+' is missing, duplicated or out of sync')
 for key in ['og:image','og:url','twitter:image']:
  values=scan.metas[key]
  if len(values)!=1 or urlsplit(values[0]).scheme!='https':issue(key+' must have one absolute HTTPS URL')
 image=scan.metas['og:image'][0] if scan.metas['og:image'] else ''
 if image:
  expected_image=settings.get('openGraph',{}).get('image','')
  if not expected_image or not image.endswith(expected_image) or not (ROOT/'src'/expected_image.lstrip('/')).is_file():issue('Open Graph image does not resolve to the configured shared image')
 pages.append({'url':url,'title':title,'titleLength':len(title),'h1':h1,'description':description,'descriptionLength':len(description),'titleMatchesH1':title_match,'canonical':scan.canonicals,'robots':robots})
for key in ['title','description']:
 duplicates=[v for v,n in collections.Counter(p[key] for p in pages).items() if v and n>1]
 if duplicates:errors.append('Duplicate '+key+' values: '+repr(duplicates))
result={'unit':args.unit,'pages':len(pages),'mode':'launch' if args.launch else 'prelaunch','indexingEnabled':settings.get('indexingEnabled',False),'errors':errors,'notes':notes,'pageMetadata':pages}
if args.output:
 args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(f'Checked {len(pages)} pages: {len(errors)} errors, {len(notes)} review notes. Indexing enabled: {result["indexingEnabled"]}.')
for msg in errors+notes:print(msg)
raise SystemExit(bool(errors))
